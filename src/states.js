const BY_CODE = new Map(STATES.map((state) => [state.code, state]));

/** The state of a postal code ("vt" or "VT"), or null. */
export function stateOf(code) {
  return (
    BY_CODE.get(
      String(code ?? '')
        .trim()
        .toUpperCase(),
    ) ?? null
  );
}
